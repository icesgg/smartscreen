// clipsync.h - 같은 계정으로 로그인한 PC 사이에서 클립보드를 넘긴다
//
// A 에서 스크린캡처하거나 무언가를 복사하면 B 에서 Ctrl+V 로 붙는다.
// 연결고리는 구글 계정 하나뿐이다 - 같은 네트워크일 필요가 없고, 블루투스도
// 폰도 개입하지 않는다. 이 앱의 자리비움 감지와는 완전히 별개의 기능이며,
// 같은 앱에 있는 이유는 계정 로그인과 Supabase 배관이 이미 여기 있기 때문이다.
//
// 서버 쪽 스키마와 그 근거는 supabase/clipboard.sql, 설계 배경은
// docs/CLIPBOARD.md 에 있다.
//
// ---------------------------------------------------------------------------
// 되울림을 막는 것이 이 기능의 핵심 문제다
// ---------------------------------------------------------------------------
// B 가 받은 내용을 자기 클립보드에 올리면 B 에서도 클립보드 변경 알림이 뜬다.
// 그걸 그대로 올리면 A 가 다시 받고, 끝나지 않는다. 두 가지로 막는다.
//
//  1. 클립보드를 우리가 바꾼 직후의 `GetClipboardSequenceNumber()` 를 적어 두고,
//     그 번호의 변경 알림은 무시한다. 윈도가 주는 정확한 값이라 이게 1차 방어다.
//  2. 마지막으로 올렸거나 받은 내용의 해시를 들고 있다가 같은 것은 올리지 않는다.
//     알림이 늦게 오거나 형식 합성(CF_BITMAP -> CF_DIB)으로 번호가 한 번 더
//     올라가는 경우를 잡는다.
//
// 그리고 서버의 행에는 올린 PC 이름이 들어 있어, 자기가 올린 것은 받지 않는다.
// 세 겹이지만 세 겹이어야 한다 - 하나라도 새면 두 PC 가 서로에게 같은 그림을
// 영원히 되던지고, 그건 사용자 눈에는 "클립보드가 멈췄다" 로 보인다.
//
// ---------------------------------------------------------------------------
// 시작할 때 남의 것을 붙이지 않는다
// ---------------------------------------------------------------------------
// 서버에 있는 가장 새 행은 어제 것일 수도 있다. 앱을 켜자마자 그것을 클립보드에
// 올리면, 사용자가 방금 복사해 둔 것을 지운다. 그래서 시작할 때는 가장 새 id 를
// 기준선으로만 적어 두고 아무것도 붙이지 않는다. 그보다 새 것만 받는다.
//
// 기준선은 "시작할 때의 조회" 가 아니라 "처음 성공한 조회" 가 적는다. 시작할
// 때 한 번만 시도하던 동안에는 그 한 번이 실패하면(네트워크가 없을 때 타일을
// 켰다) 기준선이 0 으로 남았고, 연결이 돌아온 뒤 첫 조회가 어제 것을 붙였다.
//
// 같은 이유로, 받아 오는 사이에 사용자가 여기서 무언가를 새로 복사했으면 받은
// 것을 붙이지 않고 버린다. 방금 복사한 자리에서 Ctrl+V 가 남의 옛것을 내놓으면
// 안 된다.
//
// ---------------------------------------------------------------------------
// 붙이지 못한 것은 미뤄 둔다
// ---------------------------------------------------------------------------
// 윈도가 잠겨 있으면 클립보드를 열 수 없다. 예전에는 그때 받은 것을 그대로 버렸고
// (받은 id 는 이미 지나갔으므로 다시 받지도 않는다) 잠긴 밤 사이 저쪽에서 복사한 것이
// 전부 사라졌다. 지금은 가장 새 것 하나를 쥐고 1초마다 한 번 열어 보다가 열리면
// 붙인다. 그 사이에 여기서 새로 복사했으면 버린다 - 위와 같은 이유다.
// 다른 앱이 클립보드를 쥐고 있어 못 연 것도 같은 길로 간다. 상태 줄은 까닭대로
// "잠금이 풀리면 붙여요" / "클립보드가 비면 붙여요" 라고 말한다.
//
// ---------------------------------------------------------------------------
// 보내지 않는 것
// ---------------------------------------------------------------------------
// 복사한 앱이 클립보드에 "기록하지도 다른 기기로 보내지도 말라" 는 표시를 달아
// 두었으면 읽지도 보내지도 않고, 상태 줄에 그렇게 말한다. 암호 관리자가 암호를
// 복사할 때 다는 표시다 (ExcludeClipboardContentFromMonitorProcessing,
// CanIncludeInClipboardHistory=0, CanUploadToCloudClipboard=0,
// Clipboard Viewer Ignore). 표시를 달지 않는 앱에서 복사한 암호는 여전히 넘어간다.
#pragma once
#include <string>

struct ClipSyncStatus {
    bool running = false;
    int  sent = 0;             // 이 세션에서 올린 개수
    int  received = 0;         // 이 세션에서 받아 붙인 개수
    bool lastOk = true;
    std::wstring lastMsg;      // 사람이 읽는 마지막 결과. 실패하면 상태코드가 실린다
};

// 동기화를 시작한다. 계정 세션이 있어야 한다 (session.h).
// maxBytes 보다 큰 항목은 건너뛴다 - 스크린샷 하나가 수십 MB 가 되는 경우가
// 있고(다중 모니터 전체 캡처), 그걸 매번 올리면 회선만 쓴다.
// 보낼 때와 받을 때 모두 본다. 받을 때 보지 않으면 상한을 더 크게 잡은 다른
// PC 가 올린 것을 이 PC 가 그대로 다 받는다. 0 이면 상한이 없다.
bool ClipSyncStart(const std::wstring& supabaseUrl, const std::wstring& anonKey,
                   unsigned long maxBytes);

// 멈춘다. GDI+ 를 쓰므로 GdiplusShutdown 보다 먼저 불러야 한다.
void ClipSyncStop();

bool ClipSyncRunning();
ClipSyncStatus ClipSyncGetStatus();

// ---------------------------------------------------------------------------
// 진단: 한 대에서 왕복을 확인한다 (SmartScreen.exe --clip-test)
// ---------------------------------------------------------------------------
// 올리고, 다시 조회하고, 내려받아 바이트를 비교한다. 받는 쪽과 같은 길로
// 읽는다 (조회는 본문 없이, 텍스트 본문은 그 행만 따로). 크기 상한을 주면
// 내려받기가 멈추는지도 본다. 클립보드는 건드리지 않고 스레드도 띄우지 않는다.
//
// 이게 있어야 하는 이유: 이 기능은 PC 두 대가 있어야 끝까지 시험되는데, 안 될
// 때 원인이 세 갈래다 - 내 코드, 서버 설정(clipboard.sql 을 안 돌렸거나 RLS
// 가 막는다), 그리고 상대 PC. 한 대에서 왕복이 되는 것만 확인해 두면 남은
// 것은 셋째뿐이다. 두 대를 나란히 놓고 들여다볼 수 없을 때 이 구분이 전부다.
bool ClipSyncRoundTrip(const std::wstring& supabaseUrl, const std::wstring& anonKey,
                       std::wstring& outReport);
