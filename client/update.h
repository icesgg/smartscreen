// update.h - 프로그램 자동 업데이트
//
// 왜 있나: 프로그램을 고치는 일은 잦은데, 고칠 때마다 PC 마다 zip 을 풀어
// 덮어쓰는 것은 손으로 하는 배포다. 사람이 하는 배포는 어느 PC 가 어느
// 버전인지 아무도 모르게 되는 것으로 끝난다. 그래서 새 버전은 서버에 올리고,
// 모든 PC 가 스스로 알아채서 받아 간다.
//
// 두 가지 길이 있고, 어느 길인지는 그 PC 가 기업 등록이 돼 있는지로 갈린다.
//
//  개인 PC     간단 창에 "새 버전이 있어요" 띠가 뜬다. [업데이트] 를 누르면
//              받아서 다시 시작한다. 누르기 전에는 아무것도 바뀌지 않는다.
//  기업 PC     기업 관리자가 대시보드에서 버전을 승인하면, 그 조직의 PC 들이
//              묻지 않고 받아서 다시 시작한다. 승인 안 된 새 버전은 보이기만
//              한다 ("관리자 승인을 기다려요") - 관리자가 배포 시점을 정한다.
//
// 서버 쪽 표와 그 근거는 supabase/releases.sql, 설계 배경은 docs/UPDATE.md.
//
// ---------------------------------------------------------------------------
// 믿는 것은 해시 하나다
// ---------------------------------------------------------------------------
// 이 표는 로그인 없이 읽힌다 (개인 PC 는 로그인이 없다). 그래서 파일이 어디에
// 있든 누구나 내려받을 수 있고, 그건 의도한 것이다 - exe 는 어차피 나눠 주는
// 물건이다. 대신 어느 exe 가 진짜인지는 행에 박힌 SHA-256 으로만 정한다.
// 행을 쓸 수 있는 사람은 release_admins 뿐이고, 그것이 이 기능의 유일한
// 신뢰 경계다. 파일 저장소가 통째로 바뀌어도 해시가 다르면 받지 않는다.
//
// 그 해시는 내려받을 때 한 번, 바꿔 넣는 순간 한 번 더 잰다. 내려받은 파일이
// %APPDATA% 에 잠깐 놓여 있는 사이에 바뀌었으면 두 번째에서 걸린다.
//
// ---------------------------------------------------------------------------
// 실행 중인 exe 는 자기를 덮어쓸 수 없다
// ---------------------------------------------------------------------------
// 그래서 자기 exe 를 %APPDATA%\SmartScreen\update\updater.exe 로 복사해 두고,
// 그 복사본을 `--apply-update` 로 띄운 뒤 정상 종료한다. 복사본은 원래
// 프로세스가 끝나기를 기다렸다가 파일을 바꾸고 새 exe 를 다시 띄운다. 별도
// updater 프로그램을 만들지 않은 이유는, 그것도 배포해야 하는 파일 하나가 더
// 생기기 때문이다 - 배포를 없애려는 기능이 배포할 것을 늘리면 안 된다.
//
// 바꾸기 전의 exe 는 `SmartScreen.exe.bak` 으로 남긴다. 새 exe 가 무사히 떠서
// UpdateCleanupAfterStart() 까지 오면 그때 지운다. 새 exe 가 시작조차 못 하면
// .bak 이 남아 있어 손으로 되돌릴 수 있다.
//
// ---------------------------------------------------------------------------
// 실패는 기억해야 한다
// ---------------------------------------------------------------------------
// 적용에 실패하면 복사본은 예전 exe 를 다시 띄운다. 그 exe 가 아무것도 모르면
// 같은 버전을 다시 받아 다시 적용하러 종료하고, 그게 끝없이 반복된다 - 기업
// PC 는 묻지 않고 적용하므로 특히 그렇다. 그래서 복사본은 실패한 버전과 이유를
// %APPDATA%\SmartScreen\update\failed-<버전>.txt 에 적고, 다음 확인은 그 버전을
// "실패함" 으로만 보여 준다. 사용자가 [다시 시도] 를 누르거나 더 새 버전이
// 나올 때까지 저절로 다시 하지 않는다.
//
// 같은 이유로 관리자 권한을 요구하는 폴더(Program Files)에서는 자동 적용을
// 하지 않는다. UAC 창을 띄우고 기다리는 동안 앱은 꺼져 있고 화면은 아무도
// 지키지 않는다. 그 경우는 "이 폴더에는 자동 업데이트를 못 해요" 로 끝내고,
// 사용자 폴더로 옮기라고 안내한다 (README 10장).
//
// ---------------------------------------------------------------------------
// 화면을 가리는 중에는 다시 시작하지 않는다
// ---------------------------------------------------------------------------
// 다시 시작하는 1~2초 동안 검은 화면이 사라진다. 자리를 비운 사람의 화면을
// 지키는 것이 이 프로그램의 일인데, 업데이트가 그 틈을 내면 안 된다. 그래서
// 준비가 끝나도 화면이 가려져 있으면 풀릴 때까지 기다린다 (main.cpp 의
// UpdateTick).
#pragma once
#include <string>

enum class UpdatePhase {
    Idle,          // 아직 확인한 적 없음
    Checking,      // 서버에 물어보는 중
    UpToDate,      // 이 버전이 가장 새 것
    Pending,       // (기업) 새 버전이 있지만 관리자가 아직 승인하지 않음
    Available,     // 받을 수 있는 새 버전이 있음. 개인 PC 는 여기서 사용자를 기다린다
    Downloading,
    Ready,         // 내려받고 해시까지 맞음. 다시 시작만 남았다
    Applying,      // updater 를 띄웠고 이 프로세스는 곧 끝난다
    Failed,        // 확인·내려받기·적용 중 하나가 실패. msg 에 이유. [다시 시도] 로 재개
};

struct UpdateStatus {
    UpdatePhase  phase = UpdatePhase::Idle;
    std::wstring version;       // 후보 버전. Pending/Available 이후에 채워진다
    std::wstring notes;         // 배포 메모 (첫 줄만 화면에 보인다)
    std::wstring msg;           // 사람이 읽는 마지막 결과. 실패하면 이유가 실린다
    int          progressPct = 0;
    bool         autoApply = false;   // 기업 PC 에서 승인된 버전 = 묻지 않고 적용
    bool         dismissed = false;   // 이 상태에 [나중에] 를 눌렀다
    bool         fromMarker = false;  // Failed 가 지난번 적용 실패 기록(failed-<버전>.txt)에서 왔다
    unsigned long long checkedTick = 0;   // 마지막 확인이 끝난 GetTickCount64
};

// 앱을 켤 때 한 번. orgId 가 비어 있으면 개인 PC 로 본다.
// notifyWnd 는 HWND 다 - 이 헤더가 windows.h 를 끌어오지 않으려고 void* 로 받는다
// (auth.h 와 같은 이유: 헤더 순서 문제).
// 상태가 바뀔 때마다 notifyWnd 에 notifyMsg 를 PostMessage 한다.
void UpdateInit(const std::wstring& supabaseUrl, const std::wstring& anonKey,
                const std::wstring& orgId, const std::wstring& channel,
                void* notifyWnd, unsigned notifyMsg);

// UpdateInit 이 불렸는지 (updateCheck=0 이면 안 불린다). UI 가 단추 글을 정하는 데 쓴다.
bool UpdateEnabled();

// 서버에 새 버전이 있는지 묻는다. 작업 스레드에서 돌고 바로 돌아온다.
// 기업 PC 에서 승인된 버전을 찾으면 이어서 내려받기까지 한다.
// 이미 다른 작업이 돌고 있으면 아무 일도 하지 않는다.
// 손으로 누른 확인(manual)만 실패를 띠에 띄운다. 한 시간마다 도는 확인이
// 오프라인이라고 띠를 띄우면, 닫을 것도 없는 "실패" 가 하루 종일 걸려 있다.
// 손으로 누른 것은 전에 [나중에] 를 눌렀어도 이번 결과를 보여 준다 - 결과를 보여
// 달라고 누른 것이다.
void UpdateCheckAsync(bool manual);

// 받을 후보(버전·경로·해시)가 정해져 있나. [다시 시도] 가 "다시 묻기" 와
// "다시 받기" 중 무엇을 할지 이걸로 가른다 - version 만 보면 틀린다 (Pending
// 은 version 은 있고 후보는 없다).
bool UpdateHasCandidate();

// Available(또는 Failed) 에서 후보를 내려받는다. 개인 PC 에서 [업데이트] 가 부른다.
// 이미 검증된 파일이 있으면 다시 받지 않고 바로 Ready 로 간다.
// 그 버전의 실패 기록(failed-<버전>.txt)은 여기서 지운다 - 사용자가 다시 하라고 했다.
void UpdateDownloadAsync();

// Ready 에서. updater 를 띄우고 true 를 돌려주면 호출한 쪽이 앱을 정상 종료해야
// 한다. UI 스레드에서 부른다 - 종료 절차가 UI 스레드의 것이기 때문이다.
// 실패하면 Failed 로 바꾼다 (띠에 이유가 뜨고 [다시 시도] 가 된다).
bool UpdateLaunchApplier(std::wstring& outErr);

// [나중에]. 지금 보이는 띠를 감춘다. 후보 버전이 있으면 그 버전에 대해 계속
// 감추고, 없으면(오프라인 실패 같은 것) 다음 확인 결과가 나올 때까지만 감춘다.
void UpdateDismiss();

UpdateStatus UpdateGetStatus();
bool         UpdateBusy();       // 작업 스레드가 돌고 있다

// 새 exe 가 무사히 떴을 때 지난 것들을 치운다: <exe>.bak, 내려받은 파일.
// 실패 기록(failed-*.txt)은 지우지 않는다 - 실패한 뒤 다시 뜬 예전 exe 가
// 그걸 봐야 한다.
void UpdateCleanupAfterStart();

// 종료. 작업 스레드를 기다린다 (최대 몇 초).
void UpdateShutdown();

// `SmartScreen.exe --apply-update <pid> <src> <dst> --sha <hex> --ver <버전> [--no-relaunch]`
// 복사본 exe 로 실행되는 쪽. 뮤텍스보다 먼저 처리해야 한다 (원래 프로세스가
// 아직 살아 있을 때 시작된다). 돌려주는 값이 프로세스 종료 코드다.
//
// 아무 파일이나 바꾸는 도구가 되지 않도록 세 가지를 요구한다: src 는
// %APPDATA%\SmartScreen\update\ 안, dst 의 파일 이름은 SmartScreen.exe, 그리고
// src 의 해시가 --sha 와 같아야 한다.
int UpdateApplyMain(int argc, wchar_t** argv);
